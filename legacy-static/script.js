const header = document.querySelector("[data-header]");
const toTop = document.querySelector("[data-to-top]");
const navToggle = document.querySelector("[data-nav-toggle]");
const nav = document.querySelector("[data-nav]");

function updateChrome() {
  const scrolled = window.scrollY > 20;
  header?.classList.toggle("is-scrolled", scrolled);
  toTop?.classList.toggle("visible", window.scrollY > 600);
}

window.addEventListener("scroll", updateChrome, { passive: true });
updateChrome();

navToggle?.addEventListener("click", () => {
  const isOpen = nav?.classList.toggle("is-open");
  navToggle.setAttribute("aria-expanded", String(Boolean(isOpen)));
});

toTop?.addEventListener("click", () => window.scrollTo({ top: 0, behavior: "smooth" }));

const revealItems = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}

const track = document.querySelector("[data-carousel-track]");
document.querySelector("[data-carousel-next]")?.addEventListener("click", () => {
  track?.scrollBy({ left: Math.round(track.clientWidth * 0.82), behavior: "smooth" });
});
document.querySelector("[data-carousel-prev]")?.addEventListener("click", () => {
  track?.scrollBy({ left: -Math.round(track.clientWidth * 0.82), behavior: "smooth" });
});

const filterButtons = document.querySelectorAll("[data-filter]");
const projectCards = document.querySelectorAll("[data-project-card]");
filterButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const filter = button.dataset.filter;
    filterButtons.forEach((item) => item.classList.remove("active"));
    button.classList.add("active");
    projectCards.forEach((card) => {
      const categories = card.dataset.category || "";
      card.classList.toggle("is-hidden", filter !== "all" && !categories.includes(filter));
    });
  });
});

const showreelModal = document.querySelector("[data-showreel-modal]");
document.querySelector("[data-open-showreel]")?.addEventListener("click", () => {
  showreelModal?.classList.add("is-open");
  showreelModal?.setAttribute("aria-hidden", "false");
});

document.querySelectorAll("[data-close-modal]").forEach((button) => {
  button.addEventListener("click", () => {
    showreelModal?.classList.remove("is-open");
    showreelModal?.setAttribute("aria-hidden", "true");
  });
});

const caseOverlay = document.querySelector("[data-case-overlay]");
const caseImage = document.querySelector("[data-case-image]");
const caseCategory = document.querySelector("[data-case-category]");
const caseTitle = document.querySelector("[data-case-title]");
const caseDescription = document.querySelector("[data-case-description]");
const caseScope = document.querySelector("[data-case-scope]");
const caseImpact = document.querySelector("[data-case-impact]");
const caseLink = document.querySelector("[data-case-link]");

document.querySelectorAll(".open-case").forEach((button) => {
  button.addEventListener("click", () => {
    const project = projects[button.dataset.project];
    if (!project) return;
    if (caseImage) {
      caseImage.setAttribute("src", project.image);
      caseImage.setAttribute("alt", project.title);
    }
    if (caseCategory) caseCategory.textContent = project.category;
    if (caseTitle) caseTitle.textContent = project.title;
    if (caseDescription) caseDescription.textContent = project.description;
    if (caseScope) caseScope.textContent = project.scope;
    if (caseImpact) caseImpact.textContent = project.impact;
    if (caseLink) caseLink.setAttribute("href", `project-detail.html?project=${button.dataset.project}`);
    caseOverlay?.classList.add("is-open");
    caseOverlay?.setAttribute("aria-hidden", "false");
  });
});

document.querySelector("[data-close-case]")?.addEventListener("click", () => {
  caseOverlay?.classList.remove("is-open");
  caseOverlay?.setAttribute("aria-hidden", "true");
});

document.addEventListener("keydown", (event) => {
  if (event.key !== "Escape") return;
  showreelModal?.classList.remove("is-open");
  showreelModal?.setAttribute("aria-hidden", "true");
  caseOverlay?.classList.remove("is-open");
  caseOverlay?.setAttribute("aria-hidden", "true");
});

function setText(selector, value) {
  const node = document.querySelector(selector);
  if (node && value) node.textContent = value;
}

function setImage(selector, src, alt) {
  const node = document.querySelector(selector);
  if (!node || !src) return;
  node.setAttribute("src", src);
  node.setAttribute("alt", alt);
}

function hydrateDetailPage() {
  if (!document.querySelector("[data-detail-page]")) return;
  const params = new URLSearchParams(window.location.search);
  const key = params.get("project") || "science-city";
  const project = projects[key] || projects["science-city"];
  document.title = `${project.title} | Chromosome Designs`;

  setImage("[data-detail-image]", project.image, project.title);
  setText("[data-detail-category]", project.category);
  setText("[data-detail-title]", project.title);
  setText("[data-detail-summary]", project.summary);
  setText("[data-detail-overview-title]", project.overviewTitle);
  setText("[data-detail-overview]", project.description);
  setText("[data-detail-typology]", project.typology);
  setText("[data-detail-services]", project.services);
  setText("[data-detail-audience]", project.audience);
  setText("[data-detail-problem-title]", project.problemTitle);
  setText("[data-detail-problem]", project.problem);
  setText("[data-detail-response]", project.response);
  setText("[data-detail-impact-title]", project.impactTitle);
  setText("[data-detail-impact]", project.impact);

  const materialList = document.querySelector("[data-detail-materials]");
  if (materialList) {
    materialList.innerHTML = "";
    project.materials.forEach((material) => {
      const item = document.createElement("li");
      item.textContent = material;
      materialList.appendChild(item);
    });
  }

  setImage("[data-gallery-one]", project.gallery[0], `${project.title} gallery image one`);
  setImage("[data-gallery-two]", project.gallery[1], `${project.title} gallery image two`);
  setImage("[data-gallery-three]", project.gallery[2], `${project.title} gallery image three`);
}

hydrateDetailPage();

